  const WEEKDAYS_SHORT = {
    ru: ['ВС', 'ПН', 'ВТ', 'СР', 'ЧТ', 'ПТ', 'СБ'],
    en: ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT']
  };
  const WEEKDAYS_FULL = {
    ru: ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'],
    en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
  };
  const MONTHS = {
    ru: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
    en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
  };

  let language = 'ru';
  const listeners = new Set();

  function t(key, params) {
    const table = STRINGS[language] || STRINGS.ru;
    let value = table[key];
    if (value == null) value = STRINGS.ru[key] != null ? STRINGS.ru[key] : key;
    if (params) {
      Object.keys(params).forEach((name) => {
        value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(params[name]));
      });
    }
    return value;
  }

  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = t(element.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      element.setAttribute('placeholder', t(element.getAttribute('data-i18n-placeholder')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((element) => {
      element.setAttribute('title', t(element.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', t(element.getAttribute('data-i18n-aria-label')));
    });
    document.documentElement.lang = language;
  }

  function setLanguage(next) {
    language = next === 'en' ? 'en' : 'ru';
    applyStatic();
    listeners.forEach((callback) => callback(language));
  }

  function onLanguageChange(callback) {
    listeners.add(callback);
  }

  window.i18n = {
    t,
    getLanguage: () => language,
    setLanguage,
    applyStatic,
    onLanguageChange,
    weekdayShort: (index) => (WEEKDAYS_SHORT[language] || WEEKDAYS_SHORT.ru)[index],
    weekdayFull: (index) => (WEEKDAYS_FULL[language] || WEEKDAYS_FULL.ru)[index],
    month: (index) => (MONTHS[language] || MONTHS.ru)[index]
  };

  applyStatic();

  if (window.api && window.api.getLanguage) {
    window.api.getLanguage().then((value) => setLanguage(value));
    if (window.api.onLanguageChanged) {
      window.api.onLanguageChanged((value) => setLanguage(value));
    }
  }
